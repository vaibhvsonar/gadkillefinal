const DEVANAGARI_DIGITS: Record<string, string> = {
  '०': '0',
  '१': '1',
  '२': '2',
  '३': '3',
  '४': '4',
  '५': '5',
  '६': '6',
  '७': '7',
  '८': '8',
  '९': '9',
};

export function toEnglishDigits(str: string): string {
  return str.replace(/[०-९]/g, d => DEVANAGARI_DIGITS[d] || d);
}

export function translateText(text: string, lang: Language): string {
  if (lang === 'mr' || !text) return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  if (MR_TO_EN_MAP[trimmed]) {
    return text.replace(trimmed, MR_TO_EN_MAP[trimmed]);
  }

  let out = text;
  for (const [mr, en] of Object.entries(MR_TO_EN_MAP)) {
    if (mr.length >= 4 && out.includes(mr)) {
      out = out.split(mr).join(en);
    }
  }
  return toEnglishDigits(out);
}

const originalNodeText = new WeakMap<Text, string>();
const originalElemAttrs = new WeakMap<Element, { placeholder?: string; title?: string }>();

export function applyLanguageToDOM(lang: Language) {
  if (typeof document === 'undefined') return;

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode() as Text | null;

  while (node) {
    const parentTag = node.parentElement?.tagName;
    if (
      parentTag !== 'SCRIPT' &&
      parentTag !== 'STYLE' &&
      !node.parentElement?.closest('[data-no-translate]')
    ) {
      const current = node.nodeValue || '';
      if (!originalNodeText.has(node)) {
        if (/[\u0900-\u097F]/.test(current)) {
          originalNodeText.set(node, current);
        }
      }
      const orig = originalNodeText.get(node);
      if (orig !== undefined) {
        const target = lang === 'en' ? translateText(orig, 'en') : orig;
        if (node.nodeValue !== target) {
          node.nodeValue = target;
        }
      }
    }
    node = walker.nextNode() as Text | null;
  }

  const elements = document.querySelectorAll('input[placeholder], textarea[placeholder], [title]');
  elements.forEach(el => {
    if (!originalElemAttrs.has(el)) {
      originalElemAttrs.set(el, {
        placeholder: el.getAttribute('placeholder') || undefined,
        title: el.getAttribute('title') || undefined,
      });
    }
    const orig = originalElemAttrs.get(el);
    if (!orig) return;

    if (orig.placeholder) {
      const nextP = lang === 'en' ? translateText(orig.placeholder, 'en') : orig.placeholder;
      if (el.getAttribute('placeholder') !== nextP) {
        el.setAttribute('placeholder', nextP);
      }
    }
    if (orig.title) {
      const nextT = lang === 'en' ? translateText(orig.title, 'en') : orig.title;
      if (el.getAttribute('title') !== nextT) {
        el.setAttribute('title', nextT);
      }
    }
  });
}
